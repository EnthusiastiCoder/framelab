// Astro integration that writes dist/sw.js after the build: a small hand-written service worker (no Workbox,
// to keep the dependency tree small) that precaches the app shell so every page and tool works offline after
// the first visit.
//
// Precached: every page (as its route), the JS and CSS under /_astro/, the icons, the manifest and the bundled
// samples. NOT precached: the Whisper models under /models/ (hundreds of MB; the subtitles tool caches the one
// the user chose, on demand), WebAssembly binaries (cached at runtime on first use), Open Graph images, the
// sitemap, robots.txt and _headers.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const EXCLUDE = [/^_headers$/, /^models\//, /^vendor\//, /\.wasm$/i, /^og\//, /^sitemap.*\.xml$/, /^robots\.txt$/, /^sw\.js$/, /^404\.html$/];

/** Site paths to precache, from dist-relative file paths ('/' separators). Pages become their route. */
export function precacheList(paths) {
  const out = [];
  for (const p of paths) {
    if (EXCLUDE.some((re) => re.test(p))) continue;
    if (p === 'index.html') out.push('/');
    else if (p.endsWith('/index.html')) out.push(`/${p.slice(0, -'/index.html'.length)}`);
    else out.push(`/${p}`);
  }
  return out.sort();
}

export function renderServiceWorker(urls, version) {
  return `// Framelab service worker (generated by scripts/sw.mjs at build time). Version ${version}.
const VERSION = ${JSON.stringify(version)};
const PRECACHE = 'framelab-precache-' + VERSION;
const RUNTIME = 'framelab-runtime';
const URLS = ${JSON.stringify(urls)};

/** Pages are stored under their route without a trailing slash; a redirected response is stored clean. */
function routeKey(pathname) {
  return pathname.length > 1 ? pathname.replace(/\\/(index\\.html)?$/, '') : pathname;
}

async function clean(response) {
  if (!response.redirected) return response;
  return new Response(await response.blob(), { status: response.status, statusText: response.statusText, headers: response.headers });
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(PRECACHE).then((cache) =>
      Promise.all(
        URLS.map(async (url) => {
          const response = await fetch(url, { cache: 'reload' });
          if (!response.ok) throw new Error('precache failed: ' + url + ' ' + response.status);
          await cache.put(url, await clean(response));
        }),
      ),
    ),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const name of await caches.keys()) {
        if (name.startsWith('framelab-precache-') && name !== PRECACHE) await caches.delete(name);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Models are cached by the subtitles tool itself, only after the user chose one.
  if (url.pathname.startsWith('/models/')) return;
  if (request.headers.has('range')) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        const key = routeKey(url.pathname);
        try {
          const response = await fetch(request);
          if (response.ok && URLS.includes(key)) {
            const cache = await caches.open(PRECACHE);
            await cache.put(key, await clean(response.clone()));
          }
          return response;
        } catch (err) {
          const cache = await caches.open(PRECACHE);
          return (await cache.match(key)) ?? (await cache.match('/offline')) ?? Response.error();
        }
      })(),
    );
    return;
  }

  event.respondWith(
    (async () => {
      const cached = await caches.match(url.pathname, { ignoreSearch: true });
      if (cached) return cached;
      const response = await fetch(request);
      // Hashed build assets and vendored binaries never change: keep them for offline use after first use.
      if (response.ok && (url.pathname.startsWith('/_astro/') || url.pathname.startsWith('/vendor/'))) {
        const cache = await caches.open(RUNTIME);
        await cache.put(url.pathname, response.clone());
      }
      return response;
    })(),
  );
});
`;
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

export default function serviceWorker() {
  return {
    name: 'framelab-service-worker',
    hooks: {
      'astro:build:done': ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const files = walk(root).map((abs) => relative(root, abs).split(sep).join('/'));
        const urls = precacheList(files);
        const hash = createHash('sha256');
        for (const url of urls) {
          const rel = url === '/' ? 'index.html' : url.slice(1);
          const file = files.includes(rel) ? rel : `${rel}/index.html`;
          hash.update(url).update(readFileSync(join(root, file)));
        }
        const version = hash.digest('hex').slice(0, 12);
        writeFileSync(join(root, 'sw.js'), renderServiceWorker(urls, version));
        logger.info(`sw.js: ${urls.length} files precached (version ${version})`);
      },
    },
  };
}
